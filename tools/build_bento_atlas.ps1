# Source-specific inspected anchors; all output goes to derived PNGs/metadata.
$ErrorActionPreference='Stop'
Add-Type -AssemblyName System.Drawing
$root=Split-Path $PSScriptRoot -Parent
$out=Join-Path $root 'assets/characters/bento'
# x,y,w,h,body axis, sole Y(exclusive). Tail and extended arms are included.
$actions=@(
 @(53,21,178,283,157,297),@(369,21,176,283,473,297),@(683,21,178,283,789,297),@(999,21,182,283,1105,297),
 @(45,335,188,283,157,611),@(374,336,177,280,473,608),@(677,336,189,282,789,610),@(1003,337,180,279,1105,608),
 @(24,646,237,266,130,904),@(317,646,302,261,444,899),@(645,648,225,256,762,896),@(968,647,195,265,1080,904),
 @(53,943,193,284,155,1219),@(370,943,186,273,471,1208),@(683,944,188,283,787,1219),@(990,945,198,282,1103,1219)
)
$walk=@(
 @(46,18,135,202,112,213),@(269,18,130,202,334,213),@(491,18,132,202,556,213),@(713,18,132,202,778,213),
 @(46,236,135,202,112,430),@(269,236,137,203,334,431),@(490,236,135,202,556,430),@(719,236,129,203,778,431),
 @(33,455,158,206,111,653),@(255,457,154,204,333,653),@(477,457,158,204,555,653),@(699,456,155,205,777,653),
 @(41,675,151,208,115,875),@(267,676,139,203,337,871),@(488,676,144,207,559,875),@(712,675,139,200,781,867),
 @(46,901,135,204,112,1097),@(269,901,133,201,334,1094),@(489,901,134,204,556,1097),@(713,901,133,204,778,1097),
 @(36,1119,142,207,109,1318),@(261,1119,137,205,331,1316),@(477,1119,144,207,553,1318),@(706,1119,138,207,775,1318),
 @(19,1341,172,205,113,1538),@(247,1341,166,204,335,1537),@(465,1341,170,204,557,1537),@(692,1341,167,205,779,1538),
 @(30,1561,149,205,109,1758),@(263,1560,135,206,331,1758),@(473,1562,144,204,553,1758),@(704,1564,134,202,775,1758)
)
$meta=[ordered]@{cell=96;pivot=@(40,72);worldFeetY=22;alphaCutoff=16;idleColumns=@(0,0,0,0,0,0,0,0);images=[ordered]@{actions=@{size=@(384,384)};walk=@{size=@(384,768)}}}
foreach($name in @('actions','walk')){
 $source=if($name -eq 'actions'){'assets/characters/bento/spritesheet (2).png'}else{'assets/characters/bento/walk_8directions.png'}
 $cuts=if($name -eq 'actions'){$actions}else{$walk}
 $scale=if($name -eq 'actions'){0.225}else{0.315}
 $expected=if($name -eq 'actions'){@(1261,1247)}else{@(887,1774)}
 $sourcePath=Join-Path $root $source
 $hash=(Get-FileHash -LiteralPath $sourcePath -Algorithm SHA256).Hash
 $src=[System.Drawing.Bitmap]::FromFile($sourcePath)
 $atlas=[System.Drawing.Bitmap]::new(384,$meta.images[$name].size[1],[System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
 $frames=@()
 try {
  if($src.Width -ne $expected[0] -or $src.Height -ne $expected[1]){throw "Re-inspect changed source dimensions: $source"}
  for($i=0;$i -lt $cuts.Count;$i++){
   $c=$cuts[$i];$cx=($i%4)*96;$cy=[int][Math]::Floor($i/4)*96
   for($y=0;$y -lt 96;$y++){for($x=0;$x -lt 96;$x++){
    $sx=[int][Math]::Floor($c[4]+($x-40+0.5)/$scale)
    $sy=[int][Math]::Floor($c[5]+($y-72+1)/$scale-1)
    if($sx -lt $c[0] -or $sx -ge $c[0]+$c[2] -or $sy -lt $c[1] -or $sy -ge $c[1]+$c[3]){continue}
    # The detached bomb in release frame 9 is drawn by the real projectile path.
    if($name -eq 'actions' -and $i -eq 9 -and $sx -ge 540 -and $sy -ge 680 -and $sy -le 760){continue}
    $p=$src.GetPixel($sx,$sy);if($p.A -le 16){continue}
    $atlas.SetPixel($cx+$x,$cy+$y,$p)
   }}
   $bottom=-1;$top=96;$left=96;$right=-1
   for($y=0;$y -lt 96;$y++){for($x=0;$x -lt 96;$x++){if($atlas.GetPixel($cx+$x,$cy+$y).A -gt 16){$bottom=$y;$top=[Math]::Min($top,$y);$left=[Math]::Min($left,$x);$right=[Math]::Max($right,$x)}}}
   if($bottom -lt 0 -or $left -lt 2 -or $right -gt 93 -or $top -lt 2){throw "Clipped/empty $name frame $i"}
   $offset=71-$bottom
   if($offset -gt 0){for($y=95;$y -ge 0;$y--){for($x=0;$x -lt 96;$x++){
    $color=if($y -ge $offset){$atlas.GetPixel($cx+$x,$cy+$y-$offset)}else{[System.Drawing.Color]::Transparent}
    $atlas.SetPixel($cx+$x,$cy+$y,$color)
   }}}
   if($offset -lt 0){throw "Unexpected pixels below sole in $name frame $i"}
   $frames+=@{x=$cx;y=$cy;w=96;h=96;crop=@($c[0..3]);sourceAnchor=@($c[4..5]);normalizedOffsetY=$offset;visibleBounds=@($left,($top+$offset),$right,71)}
  }
  $atlas.Save((Join-Path $out "$name.png"),[System.Drawing.Imaging.ImageFormat]::Png)
  $meta[$name]=@{source=$source;sourceSHA256=$hash;sourceSize=$expected;scale=$scale;frames=$frames}
 } finally {$src.Dispose();$atlas.Dispose()}
 if((Get-FileHash -LiteralPath $sourcePath -Algorithm SHA256).Hash -ne $hash){throw "Original changed: $source"}
}
$json=$meta|ConvertTo-Json -Depth 8
[System.IO.File]::WriteAllText((Join-Path $out 'atlas.js'),"/* Generated by tools/build_bento_atlas.ps1; originals are preserved. */`nconst BentoAtlas = $json;`n",[System.Text.UTF8Encoding]::new($false))
Write-Output 'Built Bento: 16 action frames + 32 walking frames; shared foot pivot (40,72), world sole y=22.'
